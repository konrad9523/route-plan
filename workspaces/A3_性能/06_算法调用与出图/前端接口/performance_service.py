"""Stable Python entry point for front-end performance-comparison calls.

The front-end server passes its request dictionary to
``run_performance_comparison`` and serializes the returned dictionary as JSON.
The public request contains only network/query/algorithm selections; optimized
algorithm versions, graph preparation, and result aggregation remain behind
this module. It returns structured chart data; the Notebook draws report figures
and the frontend renders its own interactive chart.
"""

from __future__ import annotations

from collections.abc import Mapping

from performance_comparison import (
    ALGORITHMS,
    NETWORKS,
    build_frontend_response,
    run_comparison_suite,
)


_REQUEST_FIELDS = {"networks", "query_count", "algorithms", "rounds", "seed"}


def _choice_list(value, field: str, allowed: Mapping[str, object], default) -> tuple[str, ...]:
    if value is None:
        value = default
    if isinstance(value, str) or not isinstance(value, (list, tuple)):
        raise ValueError(f"{field} must be a list of IDs")
    values = tuple(value)
    if not values:
        raise ValueError(f"{field} must contain at least one ID")
    if any(not isinstance(item, str) for item in values):
        raise ValueError(f"{field} values must be strings")
    if len(set(values)) != len(values):
        raise ValueError(f"{field} must not contain duplicates")
    unknown = set(values) - allowed.keys()
    if unknown:
        raise ValueError(f"unknown {field} IDs: {sorted(unknown)}")
    return values


def _bounded_int(value, field: str, minimum: int, maximum: int) -> int:
    if type(value) is not int or not minimum <= value <= maximum:
        raise ValueError(f"{field} must be an integer in [{minimum}, {maximum}]")
    return value


def _summary_table(networks: list[dict]) -> list[dict]:
    rows = []
    for item in networks:
        graph = item["network"]
        for result in item["table"]:
            rows.append({
                "network_id": graph["id"],
                "network": graph["label"],
                "nodes": graph["nodes"],
                "directed_edges": graph["directed_edges"],
                **result,
            })
    return rows


def _chart_data(networks: list[dict]) -> list[dict]:
    rows = []
    for item in networks:
        graph = item["network"]
        for result in item["chart_data"]:
            rows.append({
                "network_id": graph["id"],
                "network": graph["label"],
                **result,
            })
    return rows


def run_performance_comparison(
    request: Mapping[str, object] | None = None,
    *,
    build_if_missing: bool = True,
) -> dict:
    """Run the selected best versions and return JSON-ready table and chart data.

    Request keys are ``networks`` (default all three scales), ``query_count``
    (1..100, default 30), ``algorithms`` (default all five), ``rounds``
    (1..5, default 3), and ``seed`` (optional unsigned 64-bit integer).
    A missing seed is generated by the runner and echoed in the response.
    """
    if request is None:
        request = {}
    if not isinstance(request, Mapping):
        raise TypeError("request must be a mapping of front-end input fields")
    unknown_fields = set(request) - _REQUEST_FIELDS
    if unknown_fields:
        raise ValueError(f"unsupported request fields: {sorted(unknown_fields)}")

    networks = _choice_list(request.get("networks"), "networks", NETWORKS, tuple(NETWORKS))
    algorithms = _choice_list(request.get("algorithms"), "algorithms", ALGORITHMS, tuple(ALGORITHMS))
    query_count = _bounded_int(request.get("query_count", 30), "query_count", 1, 100)
    rounds = _bounded_int(request.get("rounds", 3), "rounds", 1, 5)
    seed = request.get("seed")
    if seed is not None and (type(seed) is not int or not 0 <= seed < 2**64):
        raise ValueError("seed must be null or an unsigned 64-bit integer")
    if type(build_if_missing) is not bool:
        raise TypeError("build_if_missing must be bool")

    payload = run_comparison_suite(
        networks=networks,
        query_count=query_count,
        algorithms=algorithms,
        rounds=rounds,
        seed=seed,
        build_if_missing=build_if_missing,
    )
    response = build_frontend_response(payload)
    response["request"] = {
        "networks": list(networks),
        "query_count": query_count,
        "algorithms": list(algorithms),
        "rounds": rounds,
        "seed": response["networks"][0]["config"]["seed"],
    }
    response["summary_table"] = _summary_table(response["networks"])
    response["chart_data"] = _chart_data(response["networks"])
    for network in response["networks"]:
        network.pop("table")
        network.pop("chart_data")
    return response
